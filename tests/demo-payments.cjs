// Run with node tests/demo-payments.cjs. Uses a fresh temporary database, no network.
const fs = require('fs');
const path = require('path');
const os = require('os');
const vm = require('vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
function load(file, dependencies = {}) {
  const output = ts.transpileModule(fs.readFileSync(path.join(root, file), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const module = { exports: {} };
  vm.runInNewContext(output, { exports: module.exports, require: name => dependencies[name] || require(name), process, Date, Error, Math }, { filename: file });
  return module.exports;
}
const pricing = load('lib/payment-pricing.ts');
assert.equal(pricing.priceBundle(1, 'standard').totalSatang, 4900);
assert.equal(pricing.priceBundle(1, 'utopia').totalSatang, 4655);
assert.equal(pricing.priceBundle(5, 'standard').totalSatang, 24500);
assert.equal(pricing.priceBundle(5, 'utopia').totalSatang, 23275);
assert.equal(pricing.priceBundle(10, 'utopia').totalSatang, 46550);
assert.equal(pricing.priceBundle(23, 'promptpay').totalSatang, 112700);
assert.equal(pricing.priceBundle(10, 'debit').totalSatang, 49000);
for (const count of [0, -1, 1.5, 1001, NaN, Infinity, '10']) assert.throws(() => pricing.priceBundle(count, 'utopia')); 
assert.throws(() => pricing.priceBundle(1, 'fake'));
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'cally-demo-ledger-'));
process.chdir(tmp);
const ledger = load('lib/server/demo-payments.ts', { '../payment-pricing': pricing });
const first = ledger.newAccount(), second = ledger.newAccount();
assert.equal(ledger.wallet(first).balance, 3);
const qr1 = ledger.createOrder(first, 10, 'promptpay');
const qr2 = ledger.createOrder(first, 10, 'promptpay');
const qr3 = ledger.createOrder(first, 23, 'promptpay');
assert.deepEqual([qr1.qrVariant, qr2.qrVariant, qr3.qrVariant], [0, 1, 0]);
assert.equal(ledger.createOrder(second, 1, 'promptpay').qrVariant, 0, 'each wallet alternates independently');
assert.equal(ledger.wallet(first).balance, 3, 'showing QR must not add credits');
const order = ledger.createOrder(first, 5, 'utopia');
assert.throws(() => ledger.resolveOrder(second, order.id, true));
assert.equal(ledger.resolveOrder(first, order.id, true), 'demo_paid');
assert.equal(ledger.resolveOrder(first, order.id, true), 'demo_paid');
assert.equal(ledger.wallet(first).balance, 8, 'duplicate approvals must not add credits');
const rejected = ledger.createOrder(first, 1, 'standard');
assert.equal(ledger.resolveOrder(first, rejected.id, false), 'failed');
assert.equal(ledger.resolveOrder(first, rejected.id, true), 'failed');
assert.equal(ledger.wallet(first).balance, 8);
const reservations = Array.from({ length: 3 }, () => ledger.reserveSearch(second));
assert.equal(ledger.wallet(second).balance, 0);
assert.throws(() => ledger.reserveSearch(second));
ledger.finishSearch(first, reservations[0]);
assert.equal(ledger.wallet(second).balance, 0, 'cannot release another account reservation');
ledger.finishSearch(second, reservations[0]);
ledger.finishSearch(second, reservations[0]);
assert.equal(ledger.wallet(second).balance, 1, 'duplicate release must return only one credit');
const { DatabaseSync } = require('node:sqlite');
const db = new DatabaseSync(path.join(tmp, '.cally-data', 'demo-payments.sqlite'));
db.prepare("UPDATE orders SET status='pending', created=0 WHERE id=?").run(rejected.id);
assert.equal(ledger.resolveOrder(first, rejected.id, true), 'expired');
db.prepare('UPDATE searches SET created=0 WHERE id=?').run(reservations[1]);
assert.equal(ledger.wallet(second).balance, 2, 'stale reservations must return');
assert.equal(ledger.wallet(second).balance, 2, 'expiry release is idempotent');
assert.equal(ledger.wallet(first).balance, 8);
db.close();
console.log('PASS: all bundle prices, invalid inputs, account isolation, duplicate approvals, cancellation, expiry, credit reservation, nonnegative balances and idempotent release. No payment/provider requests.');
